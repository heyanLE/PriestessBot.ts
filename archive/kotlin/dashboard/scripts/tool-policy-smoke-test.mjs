import assert from 'node:assert/strict';
import { moduleUrl, model } from './v3-test-support.mjs';
const { isToolEnabled, setToolEnabled, toolMinimumPermission, setToolMinimumPermission } = await import(moduleUrl('src/models/toolPolicy.ts'));
const platform = { ...model.newPolicy(), enabled: { read: true, search: false, write: true } };
const agent = model.newPolicy();
assert.equal(isToolEnabled('read', agent, platform), true);
assert.equal(isToolEnabled('search', agent, platform), false);
setToolEnabled(platform, 'search', true);
assert.equal(isToolEnabled('search', agent, platform), true);
assert.equal(isToolEnabled('read', agent, platform), true);
setToolEnabled(agent, 'read', false);
assert.equal(isToolEnabled('read', agent, platform), false);
assert.equal(isToolEnabled('write', agent, platform), true);
setToolEnabled(platform, 'search', false);
setToolEnabled(agent, 'search', true);
assert.equal(isToolEnabled('search', agent, platform), false);
for (const name of Object.keys(platform.enabled)) setToolEnabled(platform, name, false);
assert.equal(Object.keys(platform.enabled).some(name => isToolEnabled(name, agent, platform)), false);
assert.equal(isToolEnabled('new-unknown-tool', platform), false);
const permissions = model.newPolicy();
assert.equal(toolMinimumPermission('write', permissions, 'ADMIN'), 'ADMIN');
setToolMinimumPermission(permissions, 'write', 'SUPER_ADMIN', 'ADMIN');
assert.equal(toolMinimumPermission('write', permissions, 'ADMIN'), 'SUPER_ADMIN');
setToolMinimumPermission(permissions, 'write', 'OPERATOR', 'ADMIN');
assert.equal(toolMinimumPermission('write', permissions, 'ADMIN'), 'ADMIN');
console.log('Tool switches passed: independent changes, platform boundary, Agent override and all-off persistence.');
